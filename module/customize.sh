SKIPUNZIP=0

ui_print "- Zairenkai ZKFC installer"

# SHA-256 is enforced before any payload is copied or a kernel module is staged.
# The APK installer also pins the whole ZIP hash in signed BuildConfig metadata.
verify_payload_manifest() {
  [ -s "$MODPATH/SHA256SUMS" ] || {
    ui_print "! SHA256SUMS is missing; refusing an unverified module package."
    return 1
  }
  # Detect missing or extra files, not only hash mismatches. META-INF contains
  # archive-level installer scripts which managers consume before populating
  # MODPATH; it is intentionally excluded from the installed payload manifest.
  # Installer marker files and the KMI-selected copy are runtime-created too.
  expected_count="$(awk 'NF >= 2 { n++ } END { print n + 0 }' "$MODPATH/SHA256SUMS")"
  actual_count="$(find "$MODPATH" -type f \
    ! -path "$MODPATH/SHA256SUMS" \
    ! -path "$MODPATH/META-INF/*" \
    ! -path "$MODPATH/zkfc/zkfc.ko" \
    ! -path "$MODPATH/zkfc/target-kmi" \
    ! -path "$MODPATH/disable" ! -path "$MODPATH/remove" \
    ! -path "$MODPATH/update" ! -path "$MODPATH/auto_mount" \
    ! -path "$MODPATH/skip_mount" ! -path "$MODPATH/.core" \
    2>/dev/null | wc -l | tr -d '[:space:]')"
  [ "$expected_count" = "$actual_count" ] || {
    ui_print "! Module payload has missing or unlisted files (manifest=$expected_count files=$actual_count)."
    return 1
  }
  if command -v sha256sum >/dev/null 2>&1; then
    (cd "$MODPATH" && sha256sum -c SHA256SUMS)
    return $?
  fi
  if command -v toybox >/dev/null 2>&1; then
    (cd "$MODPATH" && toybox sha256sum -c SHA256SUMS)
    return $?
  fi
  ui_print "! SHA-256 verification is unavailable on this device."
  return 1
}
if ! verify_payload_manifest; then
  abort "  module integrity verification failed; nothing was installed"
fi

ARCH64="$(getprop ro.product.cpu.abi)"
API="$(getprop ro.build.version.sdk)"
ui_print "  device abi: $ARCH64, api: $API"

if [ "$API" -lt 31 ]; then
  ui_print "! Zairenkai requires Android 12 (API 31) or newer"
  abort "  aborting"
fi

# A source checkout is not a flashable module package: the per-KMI .ko files
# are generated by the CI build and must be present in a release ZIP.
if [ ! -d "$MODPATH/lkm" ] || [ -z "$(find "$MODPATH/lkm" -type f -name 'zkfc.ko' -print -quit 2>/dev/null)" ]; then
  if [ ! -e /dev/zkfc ]; then
    ui_print "! This package contains no ZKFC kernel module (zkfc.ko)."
    ui_print "  Download the CI-built Zairenkai-module.zip for a KMI/ABI module set."
    abort "  refusing an installation that could only enable the UI without the kernel driver"
  fi
  ui_print "- No LKM payload; using the already-present built-in ZKFC endpoint."
fi

# Prefer the KMI from the kernel release; otherwise use the app handoff or
# vendor module vermagic. Never trial-load other KMI variants by Linux family alone.
KREL="$(uname -r)"
ui_print "- Kernel: $KREL"
KERNEL_FAMILY="$(echo "$KREL" | cut -d- -f1 | awk -F. 'NF >= 2 && $1 ~ /^[0-9]+$/ && $2 ~ /^[0-9]+$/ { print $1 "." $2 }')"
# uname commonly formats KMI as 5.10.198-android13-9, not android13-5.10.
ANDROID_BRANCH="$(echo "$KREL" | grep -oE 'android[0-9]+' | head -1)"
KMI=""
if [ -n "$ANDROID_BRANCH" ] && [ -n "$KERNEL_FAMILY" ]; then
  KMI="$ANDROID_BRANCH-$KERNEL_FAMILY"
fi
# A GKI banner may omit androidNN (for example 5.10.269-gki-<hash>). The app
# therefore asks for an explicit KMI and passes it through the root manager's
# installer environment. Never infer the Android branch from Linux version alone.
REQUESTED_KMI="${ZAIRENKAI_TARGET_KMI:-}"
if [ -z "$REQUESTED_KMI" ] && [ -r /data/adb/.zairenkai/target-kmi.pending ]; then
  IFS= read -r REQUESTED_KMI < /data/adb/.zairenkai/target-kmi.pending || true
  [ -z "$REQUESTED_KMI" ] || ui_print "- KMI selection received from Zairenkai installer handoff."
fi
# If the kernel banner omits androidNN, inspect installed vendor modules. This
# evidence is also used to reject a manual/app selection that contradicts the
# running firmware. Multiple distinct branches are ambiguous and fail closed.
if [ -z "$KMI" ]; then
  DETECTED_VENDOR_KMIS="$(
    for root in /vendor/lib/modules /vendor_dlkm/lib/modules /system/vendor/lib/modules /odm/lib/modules /odm_dlkm/lib/modules; do
      [ -d "$root" ] || continue
      find "$root" -type f -name '*.ko' 2>/dev/null
    done | while IFS= read -r candidate; do
      release="$(grep -a -o 'vermagic=[^[:space:]]*' "$candidate" 2>/dev/null | head -1 | sed 's/^vermagic=//')"
      branch="$(echo "$release" | grep -oE 'android[0-9]+' | head -1)"
      numeric="$(echo "$release" | cut -d- -f1)"
      family="$(echo "$numeric" | awk -F. 'NF >= 2 && $1 ~ /^[0-9]+$/ && $2 ~ /^[0-9]+$/ { print $1 "." $2 }')"
      [ -n "$branch" ] && [ "$family" = "$KERNEL_FAMILY" ] || continue
      case "$branch-$family" in
        android12-5.10|android13-5.10|android13-5.15|android14-5.15|android14-6.1|android15-6.6|android16-6.12|android17-6.18)
          printf '%s\n' "$branch-$family" ;;
      esac
    done | sort -u
  )"
  DETECTED_COUNT="$(printf '%s\n' "$DETECTED_VENDOR_KMIS" | awk 'NF { n++ } END { print n + 0 }')"
  if [ "$DETECTED_COUNT" -gt 1 ]; then
    ui_print "! Vendor modules expose multiple KMI branches: $DETECTED_VENDOR_KMIS"
    if [ -n "$REQUESTED_KMI" ]; then
      if printf '%s\n' "$DETECTED_VENDOR_KMIS" | grep -Fxq "$REQUESTED_KMI"; then
        ui_print "- Explicit KMI matches an installed vendor-module vermagic; continuing with exact payload checks."
      else
        abort "  selected KMI $REQUESTED_KMI is not present in installed vendor-module vermagic candidates"
      fi
    else
      abort "  choose an explicit KMI matching this firmware; refusing an ambiguous automatic selection"
    fi
  elif [ "$DETECTED_COUNT" -eq 1 ]; then
    if [ -n "$REQUESTED_KMI" ] && [ "$REQUESTED_KMI" != "$DETECTED_VENDOR_KMIS" ]; then
      abort "  selected KMI $REQUESTED_KMI conflicts with vendor module KMI $DETECTED_VENDOR_KMIS"
    fi
    if [ -z "$REQUESTED_KMI" ]; then
      REQUESTED_KMI="$DETECTED_VENDOR_KMIS"
      ui_print "- KMI detected from vendor module vermagic: $REQUESTED_KMI"
    fi
  fi
fi
case "$REQUESTED_KMI" in
  "") ;;
  android12-5.10|android13-5.10|android13-5.15|android14-5.15|android14-6.1|android15-6.6|android16-6.12|android17-6.18)
    REQUESTED_KMI_FAMILY="${REQUESTED_KMI#*-}"
    if [ "$REQUESTED_KMI_FAMILY" != "$KERNEL_FAMILY" ]; then
      abort "  selected KMI $REQUESTED_KMI conflicts with running Linux family ${KERNEL_FAMILY:-unknown}"
    fi
    if [ -n "$KMI" ] && [ "$KMI" != "$REQUESTED_KMI" ]; then
      abort "  selected KMI $REQUESTED_KMI conflicts with kernel banner KMI $KMI"
    fi
    KMI="$REQUESTED_KMI"
    ui_print "- Explicit target KMI selected: $KMI"
    ;;
  *) abort "  unsupported target KMI '$REQUESTED_KMI'; refusing to guess" ;;
esac
ARCH64="$(getprop ro.product.cpu.abi)"
case "$ARCH64" in
  arm64-v8a|arm64*) USER_ABI="arm64-v8a"; ABIDIR="arm64" ;;
  x86_64) USER_ABI="x86_64"; ABIDIR="x86_64" ;;
  *) abort "  unsupported device ABI '$ARCH64'; refusing to install a mismatched userspace binary" ;;
esac

module_release() {
  [ -f "$1" ] || return 0
  grep -a -o 'vermagic=[^[:space:]]*' "$1" 2>/dev/null | head -1 | sed 's/^vermagic=//'
}
module_family() {
  release="$(module_release "$1")"
  numeric="$(echo "$release" | cut -d- -f1)"
  echo "$numeric" | awk -F. 'NF >= 2 && $1 ~ /^[0-9]+$/ && $2 ~ /^[0-9]+$/ { print $1 "." $2 }'
}

# Refuse to install an inactive/misleading runtime unless the kernel already
# exposes /dev/zkfc or an exact KMI/ABI module can be selected and validated.
mkdir -p "$MODPATH/zkfc"
PRIMARY="$MODPATH/lkm/$KMI-$ABIDIR/zkfc.ko"
module_kmi() {
  release="$(module_release "$1")"
  branch="$(echo "$release" | grep -oE 'android[0-9]+' | head -1)"
  family="$(module_family "$1")"
  [ -n "$branch" ] && [ -n "$family" ] && echo "$branch-$family"
}
if [ ! -e /dev/zkfc ]; then
  if [ -z "$KMI" ]; then
    ui_print "! Kernel release has no recognizable Android KMI branch: $KREL"
    abort "  no explicit or vendor-detected KMI is available; refusing to guess between same-family modules"
  fi
  PRIMARY_FAMILY="$(module_family "$PRIMARY")"
  PRIMARY_KMI="$(module_kmi "$PRIMARY")"
  if [ ! -f "$PRIMARY" ] || [ -z "$PRIMARY_FAMILY" ] || [ "$PRIMARY_FAMILY" != "$KERNEL_FAMILY" ]; then
    ui_print "! No module validates for KMI/ABI $KMI-$ABIDIR and Linux family ${KERNEL_FAMILY:-unknown}."
    abort "  selected payload is missing or targets a different Linux family; refusing cross-family fallback"
  fi
  # Some GKI builds omit androidNN from vermagic even when CI built the module
  # for a specific KMI directory. The exact KMI/ABI path is already covered by
  # SHA256SUMS; accept a missing branch marker only for this explicitly selected
  # payload, while always rejecting a conflicting marker. insmod still performs
  # the kernel's symbol-version and module-signature checks at load time.
  if [ -n "$PRIMARY_KMI" ] && [ "$PRIMARY_KMI" != "$KMI" ]; then
    ui_print "! Selected module vermagic identifies $PRIMARY_KMI, not $KMI."
    abort "  refusing a conflicting KMI module"
  fi
  if [ -z "$PRIMARY_KMI" ]; then
    ui_print "! Module vermagic omits androidNN; selected payload path and hash match $KMI-$ABIDIR."
    ui_print "  Kernel module loading will still validate required symbols and signature."
  fi
  cp "$PRIMARY" "$MODPATH/zkfc/zkfc.ko"
  ui_print "- KMI/ABI catalog module staged: $KMI-$ABIDIR"
elif [ -n "$KMI" ] && [ -f "$PRIMARY" ] && [ "$(module_kmi "$PRIMARY")" = "$KMI" ]; then
  cp "$PRIMARY" "$MODPATH/zkfc/zkfc.ko"
  ui_print "- Exact KMI module staged: $KMI-$ABIDIR"
else
  rm -f "$MODPATH/zkfc/zkfc.ko"
  ui_print "- Existing /dev/zkfc endpoint detected; no speculative module staged."
fi
if [ -n "$KMI" ]; then
  printf '%s\n' "$KMI" > "$MODPATH/zkfc/target-kmi" || abort "  failed to persist the verified target KMI"
  chmod 0600 "$MODPATH/zkfc/target-kmi" || abort "  failed to protect the target KMI marker"
else
  rm -f "$MODPATH/zkfc/target-kmi"
fi

# Install only the userspace ABI that matches the running device. The old loop
# always tried arm64-v8a first, even on x86_64 devices, which could leave a
# present-but-unexecutable daemon and a misleading UI state.
# Some root managers extract ZIP payloads without preserving Unix executable
# bits. SHA256SUMS authenticates the bytes; check file presence here, then apply
# and verify executable permissions on the runtime copies after they are copied.
[ -s "$MODPATH/bin/$USER_ABI/zkfctl" ] || abort "  zkfctl binary missing or empty for device ABI $USER_ABI"
[ -s "$MODPATH/bin/$USER_ABI/zperfd" ] || abort "  zperfd binary missing or empty for device ABI $USER_ABI"
mkdir -p /data/adb/zkfc /data/adb/zperf/catalog /data/adb/zperf/database || abort "  cannot create runtime directories"
cp -f "$MODPATH/bin/$USER_ABI/zkfctl" /data/adb/zkfc/zkfctl || abort "  failed to install zkfctl"
chmod 0755 /data/adb/zkfc/zkfctl || abort "  failed to set zkfctl permissions"
[ -x /data/adb/zkfc/zkfctl ] || abort "  installed zkfctl is not executable"
cp -f "$MODPATH/bin/$USER_ABI/zperfd" /data/adb/zperf/zperfd || abort "  failed to install zperfd"
chmod 0755 /data/adb/zperf/zperfd || abort "  failed to set zperfd permissions"
[ -x /data/adb/zperf/zperfd ] || abort "  installed zperfd is not executable"
ui_print "- zkfctl installed ($USER_ABI)"
ui_print "- zperfd engine installed ($USER_ABI)"
if [ -d "$MODPATH/zperf/catalog" ]; then
  cp "$MODPATH"/zperf/catalog/*.toml /data/adb/zperf/catalog/ 2>/dev/null
fi
if [ -d "$MODPATH/zperf/database" ]; then
  cp -R "$MODPATH/zperf/database/." /data/adb/zperf/database/
fi
# Namespaced Scene / vtools adapter. Never overwrite another app's global hook.
if [ -f "$MODPATH/zperf/powercfg.sh" ]; then
  cp "$MODPATH/zperf/powercfg.sh" /data/adb/zperf/powercfg.sh && chmod 0755 /data/adb/zperf/powercfg.sh
  [ -f "$MODPATH/zperf/powercfg.json" ] && cp "$MODPATH/zperf/powercfg.json" /data/adb/zperf/powercfg.json
  if [ ! -e /data/powercfg.sh ] || grep -Fq '# Zairenkai <-> Scene/vtools external-scheduler contract.' /data/powercfg.sh; then
    cp "$MODPATH/zperf/powercfg.sh" /data/powercfg.sh && chmod 0755 /data/powercfg.sh
    ui_print "- Scene compatibility hook installed (/data/powercfg.sh)"
  else
    ui_print "- Preserved existing /data/powercfg.sh (not owned by Zairenkai)"
    ui_print "  Namespaced adapter remains at /data/adb/zperf/powercfg.sh"
  fi
  if [ ! -e /data/powercfg.json ] || grep -Fq '"integration": "zairenkai.scene-interop"' /data/powercfg.json || grep -Fq '"version": "zairenkai-zperfd 1.0"' /data/powercfg.json; then
    cp "$MODPATH/zperf/powercfg.json" /data/powercfg.json
  else
    ui_print "- Preserved existing /data/powercfg.json (not owned by Zairenkai)"
  fi
fi
[ -f /data/adb/zperf/mode ] || echo balance > /data/adb/zperf/mode
chmod 0700 /data/adb/zperf 2>/dev/null || true
chmod 0600 /data/adb/zperf/mode 2>/dev/null || true

# Keep the immutable payload under MODPATH: service.sh re-verifies it on every
# boot and compares the installed runtime binaries with this trusted manifest.
set_perm /data/adb/zkfc/zkfctl 0 0 0755 u:object_r:system_file:s0 2>/dev/null
[ -f /data/adb/zperf/zperfd ] && set_perm /data/adb/zperf/zperfd 0 0 0755 u:object_r:system_file:s0 2>/dev/null
set_perm_recursive "$MODPATH" 0 0 0755 0644
[ ! -f "$MODPATH/zkfc/target-kmi" ] || chmod 0600 "$MODPATH/zkfc/target-kmi"

ui_print "- Installed zkfctl to /data/adb/zkfc/zkfctl"
ui_print "- Reboot, then open the Zairenkai app"
