"""Generate the Zairenkai launcher icon and splash mark as vector drawables.

The mark is the setup's pinwheel: four comma-shaped petals around a centre
dot, the same geometry as tools/lottie/gen_setup_animations.py (petal()) and
ui/icons/ZkIcons.Mark. Outputs (app/src/main/res/drawable):

  ic_launcher_background.xml   luminous diagonal gradient (blue, violet, pink, amber)
                               with a soft highlight
  ic_launcher_foreground.xml   the white mark inside the 66 dp safe zone
  ic_launcher_monochrome.xml   the mark alone, for themed icons (Android 13+)
  ic_zk_logo.xml               splash icon: the gradient disc with the mark

    python3 tools/icon/gen_app_icon.py [--out app/src/main/res/drawable]
"""
from __future__ import annotations

import argparse
import math
from pathlib import Path

HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- SPDX-License-Identifier: LicenseRef-Zairenkai-Proprietary -->\n<!-- Generated by tools/icon/gen_app_icon.py; edit the generator, not this file. -->\n'
GRADIENT = ["#FF4C6EF5", "#FF845EF7", "#FFF06595", "#FFFFA94D"]


def petal_points(cx: float, cy: float, angle_deg: float, length: float, bend=0.55, steps=12):
    a = math.radians(angle_deg)
    pts = []
    for k in range(steps + 1):
        t = k / steps
        r = length * t
        sweep = a + bend * math.sin(math.pi * t) * (1 - 0.3 * t)
        pts.append((cx + r * math.cos(sweep), cy + r * math.sin(sweep)))
    return pts


def smooth_path(pts) -> str:
    """Catmull-Rom through the points, as cubic Beziers."""
    d = f"M{pts[0][0]:.2f},{pts[0][1]:.2f}"
    for i in range(len(pts) - 1):
        p0 = pts[max(i - 1, 0)]
        p1, p2 = pts[i], pts[i + 1]
        p3 = pts[min(i + 2, len(pts) - 1)]
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        d += f" C{c1[0]:.2f},{c1[1]:.2f} {c2[0]:.2f},{c2[1]:.2f} {p2[0]:.2f},{p2[1]:.2f}"
    return d


def mark_paths(cx: float, cy: float, length: float, width: float, color: str) -> str:
    out = []
    for k in range(4):
        d = smooth_path(petal_points(cx, cy, k * 90 - 45, length))
        out.append(f'    <path android:pathData="{d}" android:strokeColor="{color}" android:strokeWidth="{width}"\n'
                   f'        android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000" />')
    r = width * 0.62
    out.append(f'    <path android:fillColor="{color}" android:pathData="M{cx - r:.2f},{cy:.2f} a{r:.2f},{r:.2f} 0 1,0 {2 * r:.2f},0 a{r:.2f},{r:.2f} 0 1,0 {-2 * r:.2f},0 Z" />')
    return "\n".join(out)


def gradient(x0, y0, x1, y1) -> str:
    items = "\n".join(f'                <item android:offset="{i / (len(GRADIENT) - 1):.3f}" android:color="{c}" />' for i, c in enumerate(GRADIENT))
    return (f'        <aapt:attr name="android:fillColor">\n'
            f'            <gradient android:type="linear" android:startX="{x0}" android:startY="{y0}" android:endX="{x1}" android:endY="{y1}">\n'
            f'{items}\n            </gradient>\n        </aapt:attr>')


def vector(size: int, body: str, aapt=False, dp: int | None = None) -> str:
    ns = ' xmlns:aapt="http://schemas.android.com/aapt"' if aapt else ""
    dp = dp or size
    return (HEADER + f'<vector xmlns:android="http://schemas.android.com/apk/res/android"{ns}\n'
            f'    android:width="{dp}dp" android:height="{dp}dp"\n'
            f'    android:viewportWidth="{size}" android:viewportHeight="{size}">\n{body}\n</vector>\n')


def background() -> str:
    body = (f'    <path android:pathData="M0,0h108v108h-108z">\n{gradient(0, 0, 108, 108)}\n    </path>\n'
            # Soft highlight towards the top left, for a luminous feel.
            '    <path android:pathData="M-20,-20 h88 a60,60 0 0,1 -88,88 z">\n'
            '        <aapt:attr name="android:fillColor">\n'
            '            <gradient android:type="radial" android:centerX="22" android:centerY="18" android:gradientRadius="62">\n'
            '                <item android:offset="0" android:color="#40FFFFFF" />\n'
            '                <item android:offset="1" android:color="#00FFFFFF" />\n'
            '            </gradient>\n        </aapt:attr>\n    </path>')
    return vector(108, body, aapt=True)


def foreground(color="#FFFFFFFF") -> str:
    # The safe zone is a 66 dp circle; petals reach ~24 dp from the centre.
    return vector(108, mark_paths(54, 54, 24, 6.4, color))


def splash() -> str:
    # Android 12 splash icons are masked to a circle of 2/3 of the icon; draw on
    # a 240 grid. The splash screen scales the icon to its own size, so the
    # intrinsic size stays small (lint VectorRaster: at most 200 dp).
    body = (f'    <path android:pathData="M120,48 a72,72 0 1,0 0.01,0 z">\n{gradient(48, 48, 192, 192)}\n    </path>\n'
            + mark_paths(120, 120, 40, 10.5, "#FFFFFFFF"))
    return vector(240, body, aapt=True, dp=120)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(Path(__file__).resolve().parents[2] / "app/src/main/res/drawable"))
    out = Path(ap.parse_args().out)
    out.mkdir(parents=True, exist_ok=True)
    files = {
        "ic_launcher_background.xml": background(),
        "ic_launcher_foreground.xml": foreground(),
        "ic_launcher_monochrome.xml": foreground("#FF000000"),
        "ic_zk_logo.xml": splash(),
    }
    for name, text in files.items():
        (out / name).write_text(text)
        print(name)


if __name__ == "__main__":
    main()
